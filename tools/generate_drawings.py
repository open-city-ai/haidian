def mfmt(key: str, digits: int = 1) -> str:
    v = metric_value(key)
    if key in ("green_ratio", "public_space_ratio"):
        return f"{v * 100:.2f}%"
    if key in ("road_network_length_m",):
        return f"{v / 1000:.1f} km"
    if key in ("site_area_sqm", "phasing_area_sqm", "key_area_total_area_sqm"):
        return f"{v / 1e6:.2f} km²"
    if key in ("green_space_area_sqm", "public_space_area_sqm", "building_footprint_area_sqm"):
        return f"{v / 1e4:.1f} ha"
    if v == int(v):
        return f"{int(v):,}"
    return f"{v:,.{digits}f}"


