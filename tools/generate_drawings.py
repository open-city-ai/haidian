def metric_rows() -> str:
    rows = ""
    for key, lzh, len_, unit, src, conf in METRIC_LABELS:
        v = metric_value(key)
        if key in ("green_ratio", "public_space_ratio"):
            disp = f"{v * 100:.4f} ({v * 100:.2f}%)"
        elif key == "road_network_length_m":
            disp = f"{v:,.1f} m ({v/1000:.1f} km)"
        elif key in ("site_area_sqm", "phasing_area_sqm", "key_area_total_area_sqm"):
            disp = f"{v:,.1f} m² ({v/1e6:.2f} km²)"
        elif key in ("green_space_area_sqm", "public_space_area_sqm", "building_footprint_area_sqm"):
            disp = f"{v:,.1f} m² ({v/1e4:.1f} ha)"
        else:
            disp = f"{v:,.1f}" if isinstance(v, float) else str(v)
        rows += (
            f"<tr><td>{lzh}</td><td>{len_}</td><td>{disp}</td>"
            f"<td>{src}</td><td>{conf}</td></tr>"
        )
    return rows


