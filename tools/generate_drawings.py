def render_pdf(html_path: Path, out_path: Path) -> None:
    cmd = [
        CHROME, "--headless", "--disable-gpu", "--no-pdf-header-footer",
        f"--print-to-pdf={out_path.as_posix()}", html_path.as_uri(),
    ]
    r = subprocess.run(cmd, capture_output=True, text=True, check=False)
    if r.returncode != 0 or not out_path.exists():
        sys.stderr.write(r.stderr[-3000:])
        raise SystemExit(f"chrome failed for {out_path.name}")


def build_html(pages, css: str, lang: str, size_label: str) -> str:
    parts = []
    for i, p in enumerate(pages):
        fig = p["f_zh"] if lang == "zh" else p["f_en"]
        body = p["b_zh"] if lang == "zh" else p["b_en"]
        title = p["t_zh"] if lang == "zh" else p["t_en"]
        total = len(pages)
        brand = "京张月台 JINGZHANG PLATFORM · 百年京张AI创新带城市设计"
        if lang == "en":
            brand = "JINGZHANG PLATFORM · Centennial Jingzhang AI Innovation Belt"
        parts.append(
            f'<div class="page">'
            f'<header class="hdr"><span class="brand">{brand}</span>'
            f'<span class="ptitle">{title}</span>'
            f'<span class="pno">{p["no"]:02d} / {total:02d}</span></header>'
            f'<main class="body">{body}</main>'
            f'<footer class="ftr"><span class="warn">{"临时几何 provisional" if lang == "zh" else "Provisional geometry"}：{"面积与比例按 EPSG:4548 复算，官方边界发布后须重算" if lang == "zh" else "areas/ratios recomputed in EPSG:4548; recompute when official polygons publish"} · 来源 { "sources.json / metrics.json / geometry" if lang == "zh" else "sources.json / metrics.json / geometry"}</span>'
            f'<span>{"数据来源与图件由本方案脚本生成，无第三方素材" if lang == "zh" else "Figures and data generated by this submission\\u2019s scripts, no third-party assets"}</span></footer></div>'
        )
    html_doc = f"<!DOCTYPE html><html lang=\"{lang}\"><head><meta charset=\"utf-8\"><title>{size_label}</title><style>{css}</style></head><body>{''.join(parts)}</body></html>"
    return html_doc


def main() -> int:
    if not os.path.exists(CHROME):
        print(f"ERROR: chrome not found at {CHROME}", file=sys.stderr)
        return 1
    out_dir = ROOT / "drawings"
    out_dir.mkdir(exist_ok=True)

    jobs = [
        ("a3-booklet", build_booklet_pages(), CSS_A3, "A3"),
        ("a0-boards", build_boards(), CSS_A0, "A0"),
    ]
    tmp = Path(tempfile.mkdtemp(prefix="jz-drawings-"))
    try:
        for stem, pages, css, size in jobs:
            for lang, suffix in (("zh", ""), ("en", ".en")):
                html_path = tmp / f"{stem}{suffix}.html"
                html_path.write_text(build_html(pages, css, lang, size), encoding="utf-8")
                pdf_path = out_dir / f"{stem}{suffix}.pdf"
                render_pdf(html_path, pdf_path)
                print(f"wrote {pdf_path.relative_to(ROOT)} ({pdf_path.stat().st_size // 1024} KiB)")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
